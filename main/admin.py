# =============================================================================
# admin.py = 管理画面に何を表示するかの設定
#
# ▼ ★これが Django の最大の武器
#
#   ここに数行書くだけで、データを一覧・検索・追加・編集・削除できる画面が
#   完成する。自分で管理用の画面を作る必要がない。
#
#   ハッカソンでは特に効く:
#     ・デモ用のデータを画面から手で入れられる
#     ・「保存されているか」をDBツールを開かずに確認できる
#     ・管理者向け機能を作る時間をまるごと節約できる
#
#   使い方(管理者アカウントの作り方)は docs/SETUP.md にある。
#   → http://localhost:8000/admin/
#
# ▼ 新しいモデルを作ったら、ここに登録すると管理画面に出るようになる。
# =============================================================================

from django.contrib import admin

from main.models import Todo


@admin.register(Todo)
class TodoAdmin(admin.ModelAdmin):
    """Todoを管理画面で扱うときの見せ方。"""

    # 一覧に並べる列。書かないと文字が1列出るだけで見づらい。
    list_display = ("id", "title", "is_done", "user", "created_at")

    # 右側に出る絞り込み。
    list_filter = ("is_done", "created_at")

    # 上に出る検索窓。ここに書いた項目が検索対象になる。
    search_fields = ("title",)

    # 一覧の画面から直接チェックを付け外しできるようにする。
    list_editable = ("is_done",)
