# ▼ ★このアプリの決まり
#
#   1. DEBUG=True(開発モード)のときだけ INSTALLED_APPS に入る。
#      本番では読み込まれないので、消し忘れても本番には出ない。
#      デモ用の表(demo_todo)も、本番のDBには作られない。
#
#   2. トップページ("/")は、main/urls.py にまだ "" が無いときだけ引き受ける。
#      Djangoは「先に書いたURLが勝つ」ので、自分たちのトップページを
#      main/urls.py に書いた瞬間、デモは自動で出なくなる。
#      → 開発を始めるときに「デモを消す作業」は不要。
#
#   3. いつでも見たいときは /__demo で開ける(開発モードのときだけ)。
#
#   ★Djangoの「The install worked successfully!」の画面と同じ考え方です。
#     あちらも、自分でトップページを作ると自動で出なくなります。
#
# ▼ 本当に不要になったら
#
#   このフォルダごと削除して、
#     ・config/settings.py の「デモ」の3行
#     ・config/urls.py の「デモ」の3行
#   を消すだけで終わりです。
