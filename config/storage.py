# =============================================================================
# storage.py = CSS・JS・画像のファイル名に「版の印」を付ける仕掛け(本番だけ)
#
#     {% static 'css/style.css' %}  →  /static/css/style.3f9a2c1b4d5e.css
#
#   ▼ 何のためのものか
#
#     ブラウザは一度読んだCSSやJSを手元に取っておき、次からはサーバーに聞かずに
#     それを使う(本番では30日間)。速くなる代わりに、直して出し直しても
#     利用者の画面は古いままになる。
#     そこでファイル名にファイルの中身から作った印を入れる。中身が変われば名前が変わり、
#     ブラウザは「別のファイルだ」と判断して取り直す。変わらなければ手元の分を使い続ける。
#
#   ▼ 使い方
#
#     HTMLではいつも通り {% static '...' %} と書くだけ。
#     印の付いたファイルは、本番の起動時に collectstatic が自動で作る。
#     CSSの中の url(...) で読んでいる画像にも、同じように印が付く。
#
#     ★"/static/..." と直接書いても表示はされるが、印が付かないので
#       直したのに古いまま、が起きる。
#
#   ▼ ★本番でだけ起きる失敗が1つある
#
#     CSSの中の url(...) が「存在しないファイル」を指していると、collectstatic が
#     エラーで止まり、本番のアプリが起動しない(開発中は気づけない)。
#     直し方は docs/DEPLOY.md の「困ったとき」にある。
#
#   ▼ 消したいとき
#
#     このファイルを消し、settings.py の STORAGES の設定を消す。
# =============================================================================
from django.contrib.staticfiles.storage import ManifestStaticFilesStorage


class VersionedStaticStorage(ManifestStaticFilesStorage):
    """Django付属の仕掛けに、1か所だけ手を入れたもの。"""

    # ★False = HTMLの {% static %} が存在しないファイルを指していても、落とさない。
    #
    #   付属のままだと、そのページを開いた瞬間に500エラーになる。しかも本番でだけ。
    #   False にしておけば、そのファイルだけ404になり、ページ自体は表示される。
    manifest_strict = False
